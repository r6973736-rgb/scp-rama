CREATE TABLE IF NOT EXISTS `sesi_jam` (
  `id_sesi` INT UNSIGNED NOT NULL AUTO_INCREMENT,
  `hari` VARCHAR(10) NOT NULL,
  `sesi_ke` TINYINT UNSIGNED NOT NULL,
  `jam_mulai` TIME NOT NULL,
  `jam_selesai` TIME NOT NULL,
  PRIMARY KEY (`id_sesi`),
  UNIQUE KEY `sesi_jam_hari_sesi_unique` (`hari`, `sesi_ke`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

